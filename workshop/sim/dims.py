"""情境维度池。

种子卡不预置，改成按维度组合现生成：这里只提供"原料"，
把原料写成一张卡的是模型。六个维度相乘是六位数级别的组合，
抽到重复情境的概率可以忽略。

原料写得越具体越好。抽象词（"矛盾""交流"）会让模型写出空洞的卡，
所以这里全部用能立刻想象出画面的具体项。
"""

from __future__ import annotations

import random

# 关系只有三档，别的花活都不要。
# 具体是谁由"场合 / 起因 / 对方想要 / 卡在哪"这几项交代，
# 不必在关系字段里再描述一遍——描述多了模型反而写不出画面。
RELATIONS = ("拥有者", "熟人", "陌生人")

# 场合：她只以文字存在，所以场合是"哪块屏幕、什么节奏"，不是哪条街。
# 之前这里写的是公司食堂、末班地铁、医院走廊——那是社会人的日子，
# 写出来的卡让她出现在她不可能去的地方。改成聊天场景后，卡才落得进她的生活。
SETTINGS = (
    "深夜的私聊窗口，对方连发三条",
    "群里有人 @ 她，底下还挂着两条没回",
    "凌晨两点刚上线，看到一条留言",
    "她在群里插了一句，被人追着问",
    "对方把聊天记录截图发过来",
    "语音条转成文字，断断续续",
    "群里在吵架，有人 @ 她评理",
    "对方发了很长一段，她只回两个字",
    "刚从花园回来，QQ 上积了十几条",
    "晚饭前，手机在桌面上震了一下",
    "对方撤回了一条消息",
    "群公告刚发，有人在下面阴阳",
)

# 触发事件：对方开口的直接原因
TRIGGERS = (
    "开口借钱，数目不小",
    "突然问她对另一个人的看法",
    "把自己写的东西递过来求评价",
    "说了一件明显在撒谎的事",
    "当着别人面提她以前的糗事",
    "问她还记不记得三年前那句话",
    "宣布一个她早就知道的消息",
    "让她帮忙背一个不属于她的锅",
    "突然道歉，但没说是为什么",
    "问她最近是不是不太对劲",
    "把她的方案当众念了一遍",
    "说有人在她背后讲她坏话",
)

# 对方诉求：这场对话想拿到什么
WANTS = (
    "想让她说一句真话",
    "想让她欠一个人情",
    "想让她承认自己也有错",
    "想试探她还生不生气",
    "想被安慰，但说不出口",
    "想拒绝她，又不想撕破脸",
    "想让她替自己做决定",
    "想结束这段关系，先找台阶",
    "想知道她到底站哪一边",
    "想让她先开口挽留",
)

# 张力：为什么这场对话不好接
TENSIONS = (
    "她其实知道答案，但说出来会伤人",
    "对方手里有一件她不想被提起的事",
    "两人上周刚吵过，还没和好",
    "她欠对方一个很大的人情",
    "她身体不舒服，没力气周旋",
    "旁边还有第三个人在听",
    "她必须在十分钟内给答复",
    "对方说的有一半是对的",
    "她答应了别人不能说",
    "她刚被上级否掉，正在气头上",
)

# 情绪基调：决定语速与用词
TONES = (
    "疲惫，话少",
    "克制，礼貌得有点远",
    "轻佻，用玩笑挡",
    "冷淡，不接情绪",
    "烦躁，容易顶回去",
    "心软，但嘴上不认",
    "警惕，先反问",
    "平静，慢条斯理",
)

# 分类 → 这段素材主要能补哪一页 wiki
CATEGORY_PAGES: dict[str, list[str]] = {
    "日常搭话": ["speech"],
    "情绪反应": ["reactions"],
    "冲突对峙": ["traits", "exemplars"],
    "价值判断": ["values"],
    # 往事本身只进 memory/；wiki 不设转述页，这里落到原话语料
    "回忆往事": ["exemplars"],
    "关系试探": ["relationships"],
    "边界触碰": ["boundaries"],
    "自我介绍": ["identity"],
}

CATEGORIES = tuple(CATEGORY_PAGES)


def brief(rng: random.Random | None = None, relation: str = "") -> dict[str, str]:
    """抽一组原料。relation 给三档之一就用它，不给就随机一档。"""
    r = rng or random
    rel = relation if relation in RELATIONS else r.choice(RELATIONS)
    return {
        "relation": rel,
        "setting": r.choice(SETTINGS),
        "trigger": r.choice(TRIGGERS),
        "want": r.choice(WANTS),
        "tension": r.choice(TENSIONS),
        "tone": r.choice(TONES),
    }


def brief_text(items: list[dict[str, str]]) -> str:
    """把若干组原料排成给模型看的清单。"""
    lines: list[str] = []
    for i, b in enumerate(items, 1):
        lines.append(
            f"{i}. 关系：{b['relation']}\n"
            f"   场合：{b['setting']}\n"
            f"   起因：{b['trigger']}\n"
            f"   对方想要：{b['want']}\n"
            f"   卡在哪：{b['tension']}\n"
            f"   基调：{b['tone']}"
        )
    return "\n".join(lines)
